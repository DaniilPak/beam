import os from "node:os";
import path from "node:path";
import fs from "node:fs/promises";
import net from "node:net";
import { discover, type Peer } from "./discovery";
import {
  TCP_PORT, Reader, readFrame, sendFrame, writeAsync, connect, withTimeout, fmtBytes, fmtTime,
  ifaceFor, prettyIface, isIPv4, ask, Progress,
} from "./util";

const CHUNK = 8 << 20;     // work unit handed to a stream
const PIECE = 1 << 20;     // read/write size
const END = 0xffffffff;

/** Never worth sending. */
const ALWAYS_SKIP = new Set([".DS_Store", "Thumbs.db", "desktop.ini", ".Spotlight-V100", ".Trashes"]);
/** Regenerated by Unity — skipped at a Unity project's root unless --all. */
const UNITY_SKIP = new Set(["Library", "Temp", "Obj", "obj", "Logs", "Build", "Builds", "MemoryCaptures", ".vs", ".gradle"]);

interface ManFile { rel: string; abs: string; size: number; mtime: number }

async function buildManifest(inputs: string[], opts: { all: boolean; exclude: string[] }) {
  const files: ManFile[] = [];
  const excluded: string[] = [];
  const roots: string[] = [];
  const userEx = new Set(opts.exclude);

  async function walk(abs: string, rel: string) {
    const ents = await fs.readdir(abs, { withFileTypes: true });
    const isUnity = ents.some((e) => e.isDirectory() && e.name === "Assets") &&
      ents.some((e) => e.isDirectory() && e.name === "ProjectSettings");
    const toStat: [string, string][] = [];
    for (const e of ents) {
      if (ALWAYS_SKIP.has(e.name) || e.name.startsWith("._") || userEx.has(e.name)) continue;
      const a = path.join(abs, e.name), r = `${rel}/${e.name}`;
      if (e.isSymbolicLink()) { console.warn(`  skipping symlink ${r}`); continue; }
      if (e.isDirectory()) {
        if (isUnity && !opts.all && UNITY_SKIP.has(e.name)) { excluded.push(r); continue; }
        await walk(a, r);
      } else if (e.isFile()) toStat.push([a, r]);
    }
    const stats = await Promise.all(toStat.map(([a]) => fs.stat(a)));
    stats.forEach((st, k) => files.push({ abs: toStat[k]![0], rel: toStat[k]![1], size: st.size, mtime: Math.floor(st.mtimeMs) }));
  }

  for (const inp of inputs) {
    const abs = path.resolve(inp);
    const st = await fs.stat(abs).catch(() => null);
    if (!st) throw new Error(`not found: ${inp}`);
    const base = path.basename(abs);
    roots.push(base + (st.isDirectory() ? "/" : ""));
    if (st.isDirectory()) await walk(abs, base);
    else files.push({ abs, rel: base, size: st.size, mtime: Math.floor(st.mtimeMs) });
  }
  return { files, excluded, roots, total: files.reduce((a, f) => a + f.size, 0) };
}

/** Measure throughput to host over one TCP stream. Bytes/sec, or 0 on failure. */
export async function probe(host: string, port = TCP_PORT, ms = 1200): Promise<number> {
  let sock: net.Socket | undefined;
  try {
    sock = await connect(host, port, 1500);
    const r = new Reader(sock);
    sendFrame(sock, { t: "probe", ms });
    let stop = false;
    const reply = readFrame(r).finally(() => { stop = true; });
    const buf = Buffer.alloc(256 << 10);
    (async () => { while (!stop) { try { await writeAsync(sock!, buf); } catch { break; } } })();
    const res = await withTimeout(reply, ms + 5000);
    return res.bytes / (res.ms / 1000);
  } catch {
    return 0;
  } finally {
    sock?.destroy();
  }
}

export async function findPeers(): Promise<Peer[]> {
  const peers = (await discover()).filter((p) => !p.self);
  return peers;
}

/** Pick receiver + fastest network path to it. */
async function resolveTarget(to: string | undefined): Promise<{ host: string; port: number; name: string }> {
  if (to && isIPv4(to)) return { host: to, port: TCP_PORT, name: to };
  if (to && /^[\w.-]+:\d+$/.test(to)) { const [h, p] = to.split(":"); return { host: h!, port: +p!, name: to }; }

  process.stdout.write("Looking for receivers… ");
  let peers = await findPeers();
  if (to) peers = peers.filter((p) => p.name.toLowerCase().includes(to.toLowerCase()));
  if (!peers.length) {
    console.log("none found.");
    throw new Error(
      "No receiver found. On the other computer run:  beam receive\n" +
      "  • both machines must be on the same network (Wi-Fi/Ethernet/cable)\n" +
      "  • on Windows the network must be 'Private' and beam allowed in the firewall\n" +
      "  • or skip discovery:  beam send <folder> --to <ip-shown-by-receiver>");
  }
  let peer = peers[0]!;
  if (peers.length > 1) {
    console.log();
    peers.forEach((p, i) => console.log(`  ${i + 1}) ${p.name} (${p.os})  ${p.addrs.join(", ")}`));
    const n = Number(await ask("Send to which one? [1] ")) || 1;
    peer = peers[Math.min(peers.length, Math.max(1, n)) - 1]!;
  } else console.log(`found ${peer.name} (${peer.os}).`);

  const host = await fastestPath(peer);
  return { host, port: peer.port, name: peer.name };
}

export async function fastestPath(peer: Peer): Promise<string> {
  if (peer.addrs.length === 1) {
    const a = peer.addrs[0]!;
    console.log(`  via ${prettyIface(ifaceFor(a)?.name ?? "?")} → ${a}`);
    return a;
  }
  console.log("  Testing network paths:");
  let best = peer.addrs[0]!, bestSpeed = -1;
  for (const a of peer.addrs) {
    const sp = await probe(a, peer.port);
    console.log(`    ${prettyIface(ifaceFor(a)?.name ?? "?").padEnd(28)} ${a.padEnd(15)}  ${sp ? fmtBytes(sp) + "/s" : "unreachable"}`);
    if (sp > bestSpeed) { best = a; bestSpeed = sp; }
  }
  console.log(`  → using ${best}`);
  return best;
}

export async function send(inputs: string[], opts: { to?: string; streams: number; all: boolean; exclude: string[] }) {
  if (!inputs.length) throw new Error("usage: beam send <file-or-folder>... [--to <name|ip>]");
  process.stdout.write("Scanning… ");
  const man = await buildManifest(inputs, opts);
  console.log(`${man.files.length} files, ${fmtBytes(man.total)}` +
    (man.excluded.length ? `  (skipped Unity caches: ${man.excluded.map((e) => e.split("/").pop()).join(", ")} — use --all to include)` : ""));

  const target = await resolveTarget(opts.to);
  const ctl = await connect(target.host, target.port, 5000);
  const r = new Reader(ctl);
  sendFrame(ctl, {
    t: "offer", from: os.hostname(), os: process.platform, roots: man.roots, total: man.total,
    excluded: man.excluded, files: man.files.map((f) => [f.rel, f.size, f.mtime]),
  });
  console.log(`Waiting for ${target.name} to accept…`);
  const resp = await readFrame(r);
  if (resp.t !== "accept") throw new Error(`rejected: ${resp.reason ?? "unknown"}`);

  const skip = new Set<number>(resp.skip);
  const todo = man.files.map((f, i) => ({ ...f, i })).filter((f) => !skip.has(f.i));
  const bytes = todo.reduce((a, f) => a + f.size, 0);
  if (skip.size) console.log(`  ${skip.size} files already up to date on the other side`);

  // Shared work queue of (file, offset, length) chunks; big files are split so all streams stay busy.
  function* chunks() {
    for (const f of todo) {
      if (f.size === 0) continue;
      for (let off = 0; off < f.size; off += CHUNK) yield { f, off, len: Math.min(CHUNK, f.size - off) };
    }
  }
  const q = chunks();
  const nChunks = todo.reduce((a, f) => a + Math.ceil(f.size / CHUNK), 0);
  const streams = Math.max(1, Math.min(opts.streams, nChunks));
  const prog = new Progress(bytes, todo.length, "  sending  ");
  todo.forEach((f) => { if (f.size === 0) prog.fileDone(); });

  async function worker() {
    const s = await connect(target.host, target.port, 5000);
    s.on("error", () => {});
    sendFrame(s, { t: "data", sid: resp.sid });
    for (let n = q.next(); !n.done; n = q.next()) {
      const { f, off, len } = n.value;
      const h = Buffer.allocUnsafe(16);
      h.writeUInt32BE(f.i, 0); h.writeUInt32BE(len, 4); h.writeBigUInt64BE(BigInt(off), 8);
      const fh = await fs.open(f.abs, "r");
      try {
        let pos = off, rem = len, first = true;
        while (rem > 0) {
          const k = Math.min(rem, PIECE);
          const b = Buffer.allocUnsafe(k);
          const { bytesRead } = await fh.read(b, 0, k, pos);
          if (bytesRead !== k) throw new Error(`${f.rel} changed while sending`);
          await writeAsync(s, first ? Buffer.concat([h, b]) : b);
          first = false;
          prog.add(k); pos += k; rem -= k;
        }
      } finally { await fh.close(); }
      if (off + len === f.size) prog.fileDone();
    }
    const e = Buffer.alloc(16); e.writeUInt32BE(END, 0);
    await writeAsync(s, e);
    s.end();
    await new Promise((res) => s.once("close", res));
  }

  try {
    await Promise.all(Array.from({ length: streams }, worker));
    sendFrame(ctl, { t: "done", streams });
    const fin = await readFrame(r);
    prog.stop();
    ctl.end();
    if (!fin.ok) throw new Error(`${fin.missing} files did not arrive — run the same command again to resume`);
    const secs = prog.elapsed();
    if (!todo.length) return console.log(`✔ ${target.name} already has everything — nothing to send`);
    console.log(`✔ Sent ${todo.length} files (${fmtBytes(bytes)}) to ${target.name} in ${fmtTime(secs)}  —  avg ${fmtBytes(bytes / Math.max(secs, 0.001))}/s`);
  } catch (e) {
    prog.stop();
    ctl.destroy();
    throw e;
  }
}
